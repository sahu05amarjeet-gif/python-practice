# Hypotenuse of a right angle triangle

import math

a = float(input("Enter the first number: "))
b = float(input("Enter the second number: "))

c = math.sqrt(math.pow(a,2) + pow(b,2))

print(f"The hypotenuse of the circle is: {c}")